#!/usr/bin/env python3
"""Regenerate the sample QNX tool artifacts in this directory.

IMPORTANT — these are SYNTHETIC samples, not a live QNX capture.

They are produced by round-tripping the Chronoscope simulation of
``models/brake-by-wire.toml`` into the exact text shapes emitted by
``traceprinter``, ``slog2info`` and ``pidin`` on QNX SDP 8.0. Their purpose is
to let anyone exercise the importers and the model/target reconciliation loop
offline, in CI, without a QNX licence or hardware.

A real capture is obtained on a QNX 8.0 target with the commands in
``target/README.md``. ``target/README.md`` and ``docs/SUBMISSION.md`` state
explicitly which parts of this project were executed on a real target.

Run from anywhere:

    python3 examples/traces/generate.py

Only the Python standard library is used.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from chronoscope.kernel import simulate  # noqa: E402
from chronoscope.model import load_model  # noqa: E402

OUT = Path(__file__).resolve().parent
MODEL = ROOT / "models" / "brake-by-wire.toml"

HEADER = """\
# SYNTHETIC SAMPLE — generated by examples/traces/generate.py.
# Simulated Chronoscope trace rendered in QNX tool output shapes.
# NOT captured from a live QNX 8.0 target. See README.md in this directory.
"""


def _stamp(t_us: float) -> str:
    """A plausible slog2info wall-clock stamp for a monotonic offset."""
    ms = int(t_us) % 1000
    sec = int(t_us) // 1000
    return f"Jan 01 00:00:{sec:02d}.{ms:03d}"


def write_traceprinter(trace) -> None:
    (OUT / "traceprinter.txt").write_text(
        HEADER + trace.to_traceprinter_text() + "\n", encoding="utf-8")


def write_slog2info(trace) -> None:
    lines = [HEADER.rstrip(),
             "# slog2info -b chronoscope   (probe emits CHRONO <monotonic_us> ...)",
             "Jan 01 00:00:00.000 chronoscope_demo 1 CHRONO 0 chronoscope_demo "
             "ABILITY PROCMGR_AID_PRIORITY granted"]
    for j in sorted(trace.jobs, key=lambda x: (x.release_us, x.thread)):
        if j.complete_us is None:
            continue
        token = f"{j.job}#{j.index}"
        lines.append(
            f"{_stamp(j.release_us)} chronoscope_demo 1 "
            f"CHRONO {int(j.release_us)} {j.thread} JOB_RELEASE "
            f"{token} deadline={int(j.deadline_us)} prio={int(j.priority)}")
        lines.append(
            f"{_stamp(j.complete_us)} chronoscope_demo 1 "
            f"CHRONO {int(j.complete_us)} {j.thread} JOB_COMPLETE "
            f"{token} status={j.status} response={int(j.response_us or 0)}")
    lines.append("Jan 01 00:00:12.000 chronoscope_demo 1 "
                 "CHRONO 12000 chronoscope_demo STOP iterations=10")
    (OUT / "slog2info.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_chrono_bare(trace) -> None:
    """The probe's stderr fallback: bare CHRONO lines, no slog2 wrapper."""
    lines = [HEADER.rstrip()]
    for j in sorted(trace.jobs, key=lambda x: (x.release_us, x.thread)):
        if j.complete_us is None:
            continue
        token = f"{j.job}#{j.index}"
        lines.append(f"CHRONO {int(j.release_us)} {j.thread} JOB_RELEASE "
                     f"{token} deadline={int(j.deadline_us)}")
        lines.append(f"CHRONO {int(j.complete_us)} {j.thread} JOB_COMPLETE "
                     f"{token} status={j.status} response={int(j.response_us or 0)}")
    (OUT / "chrono-stderr.txt").write_text("\n".join(lines) + "\n",
                                           encoding="utf-8")


def write_pidin(model, trace) -> None:
    states = {
        "pedal_sampler": "REPLY",
        "brake_server": "RECEIVE",
        "diag_logger": "RUNNING",
        "wheel_speed_ist": "INTR",
    }
    lines = [HEADER.rstrip(),
             "# pidin -F '%P %T %n %p %S' snapshot (illustrative state column)",
             "     pid tid name               prio STATE"]
    for i, t in enumerate(model.threads, 1):
        lines.append(f"  {41000 + i:5d} {i:3d} {t.name:<20s} "
                     f"{t.priority:4d} {states.get(t.name, 'READY')}")
    (OUT / "pidin.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    # Keep trace referenced so the two files stay generated from one run.
    assert trace.jobs


def main() -> int:
    model = load_model(MODEL)
    trace = simulate(model)
    OUT.mkdir(parents=True, exist_ok=True)
    trace.to_json(OUT / "simulated-trace.json")
    write_traceprinter(trace)
    write_slog2info(trace)
    write_chrono_bare(trace)
    write_pidin(model, trace)
    for p in sorted(OUT.glob("*.txt")) + [OUT / "simulated-trace.json"]:
        print(f"  wrote {p.relative_to(ROOT)}  ({p.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
